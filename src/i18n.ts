export type MessageKey = keyof typeof messages["zh-TW"];
export type Translator = (key: MessageKey, values?: Record<string, string | number>) => string;

export function resolveInterfaceLanguage(preference: InterfaceLanguage): ResolvedLanguage {
  if (preference !== "system") return preference;
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  return languages.some((language) => language.toLowerCase().startsWith("zh")) ? "zh-TW" : "en";
}

export function createTranslator(language: ResolvedLanguage): Translator {
  return (key, values = {}) => Object.entries(values).reduce(
    (message, [name, value]) => message.split(`{${name}}`).join(String(value)),
    messages[language][key] as string,
  );
}
